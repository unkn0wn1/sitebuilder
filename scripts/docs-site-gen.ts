// Generate the docs-site reference pages from the agent gateway sources.
// Counts are read from those files. Do not hand-copy them into the pages.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')

const HTTP_METHODS = new Set(['get', 'post', 'put', 'patch', 'delete', 'options', 'head'])

export function countToolRows(markdown: string): number {
  let inTools = false
  let count = 0
  for (const line of markdown.split('\n')) {
    if (line.startsWith('## ')) {
      inTools = line.trim() === '## Tools'
      continue
    }
    if (inTools && /^\| \[`/.test(line)) count++
  }
  return count
}

export function toolTableRows(markdown: string): string[] {
  let inTools = false
  const rows: string[] = []
  for (const line of markdown.split('\n')) {
    if (line.startsWith('## ')) {
      if (inTools) break
      inTools = line.trim() === '## Tools'
      continue
    }
    if (inTools && /^\| \[`/.test(line)) rows.push(line)
  }
  return rows
}

interface OpenApiOperation {
  summary?: string
}

export function countOpenApiOperations(spec: { paths?: Record<string, Record<string, unknown>> }): number {
  return listOpenApiOperations(spec).length
}

export function listOpenApiOperations(spec: { paths?: Record<string, Record<string, unknown>> }): { method: string; path: string; summary: string }[] {
  const out: { method: string; path: string; summary: string }[] = []
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const [key, value] of Object.entries(item)) {
      if (!HTTP_METHODS.has(key.toLowerCase())) continue
      const summary = value && typeof value === 'object' && 'summary' in value ? String((value as OpenApiOperation).summary ?? '') : ''
      out.push({ method: key.toUpperCase(), path, summary })
    }
  }
  return out
}

const PLUGINS_STUB = `---
title: Plugins
---

# Plugins

There is no open plugin marketplace. Official packages are a small curated catalogue, each one signed by the Skewstone maintainers. Nothing third-party is installed unless an admin chooses it. The public demo refuses plugin archive uploads.

This page is a stub until \`docs/plugins.md\` is in the repository. The generator copies that file here when it exists.
`

const REPO_DOCS = 'https://github.com/unkn0wn1/sitebuilder/blob/main/docs'

// docs/plugins.md links to other files in docs/. On the docs site those paths do not exist.
function pluginsPageForDocs(source: string): string {
  const body = source.replace(/\[([^\]]+)\]\((?!https?:|mailto:|#|\/)([^)\s]+)\)/g, (full, label: string, href: string) => {
    const hashAt = href.indexOf('#')
    const path = hashAt === -1 ? href : href.slice(0, hashAt)
    const hash = hashAt === -1 ? '' : href.slice(hashAt)
    if (!path.endsWith('.md')) return full
    return `[${label}](${REPO_DOCS}/${path.replace(/^\.\//, '')}${hash})`
  })
  if (body.startsWith('---')) return body
  return `---\ntitle: Plugins\n---\n\n${body}`
}

export function generateDocsSite(root = repoRoot): { tools: number; operations: number } {
  const toolsMd = readFileSync(join(root, 'docs/agent-gateway-tools.md'), 'utf8')
  const spec = JSON.parse(readFileSync(join(root, 'docs/agent-gateway-openapi.json'), 'utf8')) as {
    paths?: Record<string, Record<string, unknown>>
  }
  const tools = countToolRows(toolsMd)
  const operations = listOpenApiOperations(spec)
  const guideDir = join(root, 'docs-site/guide')
  const referenceDir = join(root, 'docs-site/reference')
  mkdirSync(guideDir, { recursive: true })
  mkdirSync(referenceDir, { recursive: true })

  const pluginsSrc = join(root, 'docs/plugins.md')
  if (existsSync(pluginsSrc)) writeFileSync(join(guideDir, 'plugins.md'), pluginsPageForDocs(readFileSync(pluginsSrc, 'utf8')))
  else writeFileSync(join(guideDir, 'plugins.md'), PLUGINS_STUB)

  const toolRows = toolTableRows(toolsMd)
    .map((line) => line.replace(/\[`([^`]+)`\]\([^)]*\)/g, '`$1`'))
    .join('\n')
  writeFileSync(
    join(referenceDir, 'tools.md'),
    `---
title: Tools
---

# Agent tools

Generated from \`docs/agent-gateway-tools.md\`. This reference lists **${tools}** tools. The count is produced by the generator.

| Tool | Kind | REST | What it does |
| --- | --- | --- | --- |
${toolRows}

Field-by-field descriptions stay in the repository source. This page is regenerated by \`npm --prefix docs-site run build\`.
`,
  )

  const apiRows = operations
    .map((op) => `| \`${op.method}\` | \`${op.path}\` | ${op.summary.replace(/\|/g, '\\|')} |`)
    .join('\n')
  writeFileSync(
    join(referenceDir, 'api.md'),
    `---
title: API
---

# Agent API

Generated from \`docs/agent-gateway-openapi.json\`. This reference lists **${operations.length}** operations. The count is produced by the generator.

| Method | Path | Summary |
| --- | --- | --- |
${apiRows}

The same operations are the tools in [Tools](/reference/tools). Nothing here is copied by hand.
`,
  )

  return { tools, operations: operations.length }
}

const invoked = process.argv[1]?.includes('docs-site-gen')
if (invoked) {
  const result = generateDocsSite()
  console.log(`docs-site: ${result.tools} tools, ${result.operations} operations`)
}
