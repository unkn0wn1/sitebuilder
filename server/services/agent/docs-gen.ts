// Renders the committed reference docs from the operation table: docs/agent-gateway-tools.md and the OpenAPI JSON.
// scripts/agent-docs.ts writes them; a test fails if they are out of date.
import { ERROR_CATALOG, OPERATIONS, inputJsonSchema, toolDescription } from './operations'
import { RECIPES, SERVER_INSTRUCTIONS } from './mcp-docs'
import { buildOpenApi } from './openapi'

export const TOOLS_DOC_PATH = 'docs/agent-gateway-tools.md'
export const OPENAPI_PATH = 'docs/agent-gateway-openapi.json'

type Prop = { type?: string | string[]; description?: string; enum?: unknown[]; default?: unknown; examples?: unknown[]; minimum?: number; maximum?: number; minLength?: number; maxLength?: number }

function typeOf(p: Prop): string {
  const t = Array.isArray(p.type) ? p.type.join(' or ') : (p.type ?? 'any')
  return p.enum ? `one of ${p.enum.map((e) => JSON.stringify(e)).join(', ')}` : t
}

function propRows(name: string): string {
  const o = OPERATIONS.find((x) => x.name === name)!
  const s = inputJsonSchema(o) as { properties?: Record<string, Prop>; required?: string[] }
  const rows = Object.entries(s.properties ?? {}).map(([k, p]) => {
    const req = s.required?.includes(k) ? 'yes' : 'no'
    const bits = [p.default !== undefined ? `default ${JSON.stringify(p.default)}` : '', p.minimum !== undefined || p.maximum !== undefined ? `${p.minimum ?? ''}..${p.maximum ?? ''}` : '', p.maxLength ? `max ${p.maxLength} chars` : ''].filter(Boolean).join(', ')
    return `| \`${k}\` | ${typeOf(p)}${bits ? ` (${bits})` : ''} | ${req} | ${(p.description ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ')} |`
  })
  return rows.length ? `| Field | Type | Required | Meaning |\n| --- | --- | --- | --- |\n${rows.join('\n')}` : 'No inputs.'
}

export function renderToolsDoc(): string {
  const out: string[] = [
    '# Agent gateway: tool reference',
    '',
    '> Generated by `npm run agent-docs` from `server/services/agent/operations.ts`. Do not edit by hand: a test fails if this file is out of date.',
    '',
    'The same tools are available over MCP (`/agent/mcp`, tool names as below) and REST (`/agent/v1`, routes as below, described in `agent-gateway-openapi.json`). For how to set it up and the safety model, read [agent-gateway.md](agent-gateway.md).',
    '',
    '## What the MCP server tells every AI on connect',
    '',
    '```text',
    SERVER_INSTRUCTIONS,
    '```',
    '',
    '## Tools',
    '',
    '| Tool | Kind | REST | What it does |',
    '| --- | --- | --- | --- |',
    ...OPERATIONS.map((o) => `| [\`${o.name}\`](#${o.name}) | ${o.level} | \`${o.method} /agent/v1${o.path}\` | ${o.doc.summary} |`),
    '',
  ]
  for (const o of OPERATIONS) {
    out.push(`## ${o.name}`, '', `**${o.doc.summary}**`, '', `Kind: ${o.level}. REST: \`${o.method} /agent/v1${o.path}\`.`, '', '### Inputs', '', propRows(o.name), '', '### Description sent to the AI', '', '```text', toolDescription(o), '```', '')
  }
  out.push('## Errors', '', '| Code | HTTP | Meaning | What to do |', '| --- | --- | --- | --- |', ...ERROR_CATALOG.map((e) => `| \`${e.code}\` | ${e.http} | ${e.meaning} | ${e.recovery} |`), '')
  out.push('## Recipes', '', 'Offered over MCP as resources (`sitebuilder://recipe/<id>`) and prompts. Reproduced here so a person can read what the AI is told.', '')
  for (const r of RECIPES) out.push(`### ${r.title}`, '', `Resource: \`sitebuilder://recipe/${r.id}\`. ${r.description}`, '', '```text', r.steps, '```', '')
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

export function renderOpenApi(): string {
  return JSON.stringify(buildOpenApi(), null, 2) + '\n'
}
