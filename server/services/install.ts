// Prepare a Compose install directory: folders, a secret key, and an environment file.
// See ADR 0007 and docs/16-operations.md#install.
import { mkdirSync, existsSync, readFileSync, writeFileSync, chmodSync, symlinkSync } from 'node:fs'
import { isAbsolute, join, resolve } from 'node:path'
import { randomBytes } from 'node:crypto'
import { fileURLToPath } from 'node:url'

export const DATA_UID = 1000 // node user in the official Node image
export const DEFAULT_INSTALL_DIR = '/srv/sitebuilder'

export interface InstallOptions {
  dir: string
  origin?: string
  publicHost?: string
  builderHost?: string
  accessTeamDomain?: string
  accessAud?: string
  cloudflareZoneId?: string
  allowNoAccess?: boolean
  /** Overwrite an existing .env. Default is to leave it alone. */
  force?: boolean
}

export interface InstallLayout {
  root: string
  dataDir: string
  mediaDir: string
  siteDir: string
  envPath: string
}

export interface PreparedInstall extends InstallLayout {
  created: boolean
  secretKey: string
  env: string
}

export function installLayout(root: string): InstallLayout {
  const resolved = resolve(root)
  return {
    root: resolved,
    dataDir: join(resolved, 'data'),
    mediaDir: join(resolved, 'media'),
    siteDir: join(resolved, 'site'),
    envPath: join(resolved, '.env'),
  }
}

/** 32 random bytes, base64, as required by SITEBUILDER_SECRET_KEY. */
export function generateSecretKey(): string {
  return randomBytes(32).toString('base64')
}

export function deployDir(): string {
  return fileURLToPath(new URL('../../deploy', import.meta.url))
}

export function parseExistingSecret(envText: string): string | null {
  const match = envText.match(/^SITEBUILDER_SECRET_KEY=(.*)$/m)
  const value = match?.[1]?.trim()
  return value ? value : null
}

export function renderEnvFile(opts: InstallOptions, secretKey: string, layout: InstallLayout): string {
  const origin = opts.origin?.replace(/\/$/, '') ?? ''
  const publicHost = opts.publicHost ?? hostFromOrigin(origin, 'example.org')
  const builderHost = opts.builderHost ?? hostFromOrigin(origin, 'builder.example.org')
  const lines = [
    '# Generated by deploy/install.sh. Back up SITEBUILDER_SECRET_KEY separately from site backups.',
    `SITEBUILDER_SECRET_KEY=${secretKey}`,
    `SITEBUILDER_ORIGIN=${origin || 'https://builder.example.org'}`,
    `PUBLIC_HOST=${publicHost}`,
    `BUILDER_HOST=${builderHost}`,
    `SITEBUILDER_ACCESS_TEAM_DOMAIN=${opts.accessTeamDomain ?? ''}`,
    `SITEBUILDER_ACCESS_AUD=${opts.accessAud ?? ''}`,
    `SITEBUILDER_CLOUDFLARE_ZONE_ID=${opts.cloudflareZoneId ?? ''}`,
    opts.allowNoAccess ? 'SITEBUILDER_ALLOW_NO_ACCESS=1' : '# SITEBUILDER_ALLOW_NO_ACCESS=1',
    `SITEBUILDER_DATA_DIR=${layout.dataDir}`,
    `SITEBUILDER_MEDIA_HOST_DIR=${layout.mediaDir}`,
    `SITEBUILDER_SITE_DIR=${layout.siteDir}`,
    `SITEBUILDER_ENV_FILE=${layout.envPath}`,
    '# SITEBUILDER_BACKUP_S3_ENDPOINT=',
    '# SITEBUILDER_BACKUP_S3_BUCKET=',
    '# SITEBUILDER_BACKUP_S3_REGION=auto',
    '# SITEBUILDER_BACKUP_S3_ACCESS_KEY_ID=',
    '# SITEBUILDER_BACKUP_S3_SECRET_ACCESS_KEY=',
    '# SITEBUILDER_BACKUP_S3_PREFIX=sitebuilder/',
    '',
  ]
  return lines.join('\n')
}

function hostFromOrigin(origin: string, fallback: string): string {
  if (!origin) return fallback
  try {
    return new URL(origin).host
  } catch {
    return fallback
  }
}

const BOOTSTRAP_MAPS = ['redirects.map', 'redirect-status.map', 'cache-tags.map', 'csp.map'] as const

/** Empty maps and a `current` symlink so origin nginx can start before the first publish. */
export function writeBootstrapRelease(siteDir: string): void {
  const bootstrap = join(siteDir, 'releases', '.bootstrap')
  mkdirSync(bootstrap, { recursive: true })
  for (const name of BOOTSTRAP_MAPS) {
    const file = join(bootstrap, name)
    if (!existsSync(file)) writeFileSync(file, '')
  }
  const current = join(siteDir, 'current')
  if (!existsSync(current)) {
    symlinkSync('releases/.bootstrap', current)
  }
}

/** Create the install folders and write .env if it is missing (or if force is set). */
export function prepareInstallDir(opts: InstallOptions): PreparedInstall {
  const layout = installLayout(opts.dir)
  if (!isAbsolute(layout.root)) throw new Error('The install directory must be an absolute path.')
  mkdirSync(layout.dataDir, { recursive: true })
  mkdirSync(layout.mediaDir, { recursive: true })
  mkdirSync(join(layout.mediaDir, 'originals'), { recursive: true })
  mkdirSync(join(layout.mediaDir, 'renditions'), { recursive: true })
  mkdirSync(join(layout.siteDir, 'releases'), { recursive: true })
  // nginx mounts the site dir read-only, so the first-boot maps and current
  // symlink must exist on the host before the container starts.
  writeBootstrapRelease(layout.siteDir)

  let created = false
  let secretKey = generateSecretKey()
  if (existsSync(layout.envPath) && !opts.force) {
    const existing = readFileSync(layout.envPath, 'utf8')
    secretKey = parseExistingSecret(existing) ?? secretKey
    return { ...layout, created, secretKey, env: existing }
  }
  const env = renderEnvFile(opts, secretKey, layout)
  writeFileSync(layout.envPath, env, { encoding: 'utf8' })
  try {
    chmodSync(layout.envPath, 0o600)
  } catch {
    /* Windows or unsupported chmod. */
  }
  created = true
  return { ...layout, created, secretKey, env }
}

export function installInstructions(prepared: PreparedInstall): string {
  const compose = join(deployDir(), 'docker-compose.yml')
  const relCompose = existsSync(compose) ? compose : 'deploy/docker-compose.yml'
  return [
    `Install directory: ${prepared.root}`,
    prepared.created ? 'Wrote a new .env and generated SITEBUILDER_SECRET_KEY.' : 'Left the existing .env in place.',
    '',
    'Back up the secret key now, separately from site backups. If it is lost, stored secrets (the Google Workspace tokens, the Cloudflare token, the AI key) must be re-entered. Content is not affected.',
    '',
    'Next:',
    `  1. Edit ${prepared.envPath} and fill in Cloudflare Access (SITEBUILDER_ACCESS_TEAM_DOMAIN and SITEBUILDER_ACCESS_AUD) and the zone id.`,
    '  2. Point the public hostname and the builder hostname at this server in Cloudflare. Turn on Access on the builder hostname.',
    `  3. From the repo: docker compose --env-file ${prepared.envPath} -f ${relCompose} up -d --build`,
    '  4. Seed the first admin if this is a new site (from the repo):',
    `       SITEBUILDER_DB_PATH=${prepared.dataDir}/sitebuilder.db npm run seed`,
    '',
  ].join('\n')
}

export function defaultOptionsFromArgs(args: string[]): InstallOptions {
  const opts: InstallOptions = { dir: DEFAULT_INSTALL_DIR }
  for (let i = 0; i < args.length; i++) {
    const a = args[i]!
    const next = args[i + 1]
    if (a === '--dir' && next) {
      opts.dir = next
      i++
    } else if (a === '--origin' && next) {
      opts.origin = next
      i++
    } else if (a === '--public-host' && next) {
      opts.publicHost = next
      i++
    } else if (a === '--builder-host' && next) {
      opts.builderHost = next
      i++
    } else if (a === '--access-team' && next) {
      opts.accessTeamDomain = next
      i++
    } else if (a === '--access-aud' && next) {
      opts.accessAud = next
      i++
    } else if (a === '--zone' && next) {
      opts.cloudflareZoneId = next
      i++
    } else if (a === '--allow-no-access') {
      opts.allowNoAccess = true
    } else if (a === '--force') {
      opts.force = true
    }
  }
  return opts
}

/** Used only so tests can assert the compose file points at the expected volumes. */
export function readComposeTemplate(): string {
  return readFileSync(join(deployDir(), 'docker-compose.yml'), 'utf8')
}

